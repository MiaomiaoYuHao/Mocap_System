// test_assoc_fragments.cpp —— 关联器分片的快速体检
//
// 【用法】不用链接、不用跑，语法检查就够：
//     g++ -std=c++17 -I src -fsyntax-only tests/test_assoc_fragments.cpp
//   实测约 0.5 秒。相比之下整个工程要连 Qt 一起编，几分钟起步——
//   改一行 .ipp 就等几分钟，没人会等，于是也就没人检查。
//
// 【为什么不能逐个分片单独检查】我一开始是那么写的，写完才发现走不通：
// 分片之间【本来就共享状态】。最典型的是 api.ipp 里的 resetDorsumRigid()，
// 它要把每一组的状态都清干净，于是必然碰到 dorsum.ipp 里的 dorsum_。
// 这不是切错了——一个"复位全部"的函数就该横跨所有组，硬把它拆开反而会
// 制造出"新增状态忘了复位"这类最难查的 bug。
//
// 所以这里做的是【整体装配检查】：把八个分片按真实顺序装进类里编一遍。
// 它能挡住绝大多数手改引入的错误（语法、拼错的成员名、access 用错、
// 分片顺序装反），代价是半秒。跨 TU 的问题仍然要整体编译才发现。
// ===========================================================================
#include "estimate/HandSkeletonAssociator.hpp"

int main() {
    // 只要上面这行编过了，八个分片就是自洽的。
    // 这里再实例化一次，顺带验证类是完整可构造的（不只是声明合法）。
    static_assert(sizeof(mocap::hm20::Hm20SkeletonAssociator) > 0,
                  "关联器类体没装配起来——检查 Hm20Assoc_*.ipp 的 include 顺序");
    return 0;
}
